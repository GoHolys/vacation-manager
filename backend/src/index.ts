/**
 * Vacation Manager API — entry point.
 *
 * Built on the Common Event Framework (CEF): `handler` is an AWS Lambda handler that accepts
 * API Gateway v1/v2, SQS, S3 or direct-invocation events, normalised by CEF into a single
 * `CommonEvent` and routed via `root.yaml`. With `--local` the same handler is served by
 * CEF's built-in HTTP dev server — one code path for local development and the cloud.
 */
import 'reflect-metadata';
import { loadEnv } from 'commoneventframework';

// Load .env / .env.local before anything reads configuration.
const envReady = loadEnv();

// Registers every `x-handler` / `x-inputParser` referenced in root.yaml (generated by cef-gen-handlers).
import './generated/HandlerRegistry';

import path from 'node:path';
import {
  type APIGatewayProxyStructuredResultV2,
  buildCommonEvent,
  type Context,
  setLambdaContext,
  startDevServer,
} from 'commoneventframework';
import type { CommonEvent, LambdaEvent } from 'commoneventframework/dist/types/commonEvent';
import { getApplication } from './bootstrap/application';
import { createHttpKernel } from './http/http-kernel';
import { RouteSecurity } from './http/route-security';

// root.yaml sits next to this file both in src/ (tsx) and dist/ (compiled build).
const ROOT_YAML = path.join(__dirname, 'root.yaml');

const kernel = createHttpKernel({
  routeSecurity: RouteSecurity.fromOpenApiFile(ROOT_YAML),
  getApplication,
});

/**
 * CEF locates root.yaml relative to the process entry script by default. Passing the path on the
 * first call makes routing independent of the launcher (tsx, node, Lambda, test runners);
 * CEF caches the parsed routes for subsequent calls.
 */
let routesLoaded = false;
function toCommonEvent(event: LambdaEvent): CommonEvent {
  if (routesLoaded) return buildCommonEvent(event);
  const commonEvent = buildCommonEvent(event, ROOT_YAML);
  routesLoaded = true;
  return commonEvent;
}

export const handler = async (
  event: LambdaEvent,
  context: Context,
): Promise<APIGatewayProxyStructuredResultV2> => {
  await envReady;
  await setLambdaContext(context);
  return kernel(toCommonEvent(event));
};

async function startLocalServer(): Promise<void> {
  await envReady;
  // Fail fast: validate configuration and connect to PostgreSQL before accepting traffic.
  const app = await getApplication();

  // The CEF dev server reads its port from argv[3] (`index.ts --local <port>`); default to PORT.
  process.argv[3] ??= String(app.config.port);
  startDevServer(handler);
  const baseUrl = `http://localhost:${process.argv[3]}`;
  app.logger.info(`🚀 API ready on ${baseUrl}  ·  docs: ${baseUrl}/doc`);

  const shutdown = async (signal: string) => {
    app.logger.info({ signal }, 'shutting down');
    await app.shutdown().catch(() => undefined);
    process.exit(0);
  };
  process.once('SIGINT', () => void shutdown('SIGINT'));
  process.once('SIGTERM', () => void shutdown('SIGTERM'));
}

if (process.argv.includes('--local')) {
  startLocalServer().catch((error: unknown) => {
    console.error('❌ Failed to start the API:', error instanceof Error ? error.message : error);
    process.exit(1);
  });
}
